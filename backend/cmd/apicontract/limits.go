// limitsDocument holds the rules the interface repeats so that a field stops
// at a bound instead of being refused after it. Each entry is named by its Go
// identifier, and the interface's tests compare their constants with it.
type limitsDocument struct {
	About string `json:"about"`
	// Limits are counts, lengths and sizes, in the unit the identifier names.
	Limits map[string]int `json:"limits"`
	// DurationsMs are spans in milliseconds.
	DurationsMs map[string]int64 `json:"durationsMs"`
	// ContestTransitions maps a status to the ones reachable from it.
	ContestTransitions map[string][]string `json:"contestTransitions"`
	// Patterns are regular expressions RE2 and JavaScript read alike.
	Patterns map[string]string `json:"patterns"`
}

func limits() ([]byte, error) {
	out, err := json.MarshalIndent(limitsDocument{
		About: "Bounds the interface repeats so that a field stops at them. Generated by " +
			"cmd/apicontract from the Go identifiers each entry is named by; run `make api-contract` " +
			"after changing one. lib/api/limits-contract.test.ts compares the interface's constants " +
			"with this file, so a bound changed on one side only fails a test.",
		Limits: map[string]int{
			"archive.MaxPageSize":                   archive.MaxPageSize,
			"archive.MaxQueryRunes":                 archive.MaxQueryRunes,
			"audit.MaxPageSize":                     audit.MaxPageSize,
			"clarifications.MaxAnnouncementRunes":   clarifications.MaxAnnouncementRunes,
			"clarifications.MaxAnswerRunes":         clarifications.MaxAnswerRunes,
			"clarifications.MaxOpenPerRegistration": clarifications.MaxOpenPerRegistration,
			"clarifications.MaxPageSize":            clarifications.MaxPageSize,
			"clarifications.MaxQuestionRunes":       clarifications.MaxQuestionRunes,
			"connector.MaxReturnPathLength":         connector.MaxReturnPathLength,
			"contests.MaxGracePeriodMin":            contests.MaxGracePeriodMin,
			"contests.MaxICPCPenaltyMin":            contests.MaxICPCPenaltyMin,
			"contests.MaxPenaltyPct":                contests.MaxPenaltyPct,
			"contests.MaxPrizePlaces":               contests.MaxPrizePlaces,
			"contests.MaxQuestionTitleRunes":        contests.MaxQuestionTitleRunes,
			"contests.MinDirectoryQueryLength":      contests.MinDirectoryQueryLength,
			"covers.MaxAttributionLen":              covers.MaxAttributionLen,
			"monitor.MaxBatchEvents":                monitor.MaxBatchEvents,
			"monitor.MaxFeedPage":                   monitor.MaxFeedPage,
			"monitor.MaxPasteTextRunes":             monitor.MaxPasteTextRunes,
			"monitor.MaxQuerySearchRunes":           monitor.MaxQuerySearchRunes,
			"provisioning.MaxScriptBytes":           provisioning.MaxScriptBytes,
			"queryrunner.MaxHistoryLimit":           queryrunner.MaxHistoryLimit,
			"recovery.TokenLength":                  recovery.TokenLength,
			"registrations.MaxEmailBytes":           registrations.MaxEmailBytes,
			"registrations.MaxNameRunes":            registrations.MaxNameRunes,
			"settings.MaxFeedbackURLLength":         settings.MaxFeedbackURLLength,
			"signup.CodeDigits":                     signup.CodeDigits,
			"users.MaxBulkAccounts":                 users.MaxBulkAccounts,
			"users.MaxEmailLength":                  users.MaxEmailLength,
			"users.MaxFullNameLength":               users.MaxFullNameLength,
			"users.MaxImportRows":                   users.MaxImportRows,
			"users.MaxPageSize":                     users.MaxPageSize,
			"users.MinPasswordLength":               users.MinPasswordLength,
			"workspace.MaxNotesRunes":               workspace.MaxNotesRunes,
			"workspace.MaxTabBodyBytes":             workspace.MaxTabBodyBytes,
			"workspace.MaxTabs":                     workspace.MaxTabs,
			"workspace.MaxTitleRunes":               workspace.MaxTitleRunes,
		},
		DurationsMs: map[string]int64{
			"monitor.MinAway":       monitor.MinAway.Milliseconds(),
			"signup.CodeLifetime":   signup.CodeLifetime.Milliseconds(),
			"signup.ResendCooldown": signup.ResendCooldown.Milliseconds(),
		},
		ContestTransitions: contests.Transitions(),
		Patterns: map[string]string{
			"users.ChosenLoginPattern": users.ChosenLoginPattern,
		},
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode the limits: %w", err)
	}
	return append(out, '\n'), nil
}
