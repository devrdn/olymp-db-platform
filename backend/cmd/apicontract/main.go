// Command apicontract writes what the interface must agree with the API on:
// the error codes it checks its translations against, and the bounds it
// repeats so that a field stops at them (limits.go). The code catalog is
// complete by construction: httpx.Error accepts only declared codes.
//
// It is generated, committed and checked by a test:
//
//	make api-contract
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"

	// Imported to declare codes at init; every package with codes must be
	// linked in.
	_ "github.com/devrdn/olymp-db-platform/backend/internal/api"
	"github.com/devrdn/olymp-db-platform/backend/internal/platform/httpx"
)

// contracts are the files written, each relative to the repository root,
// under docs/ because they belong to neither application.
var contracts = []struct {
	file  string
	build func() ([]byte, error)
}{
	{"docs/api/error-codes.json", errorCodes},
	{"docs/api/limits.json", limits},
}

// contractPath resolves file by walking up to go.mod, since `go run` and
// `go test` start in different directories.
func contractPath(file string) (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("locate the working directory: %w", err)
	}

	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return filepath.Join(filepath.Dir(dir), file), nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("no go.mod above the working directory")
		}
		dir = parent
	}
}

// document is an object rather than a bare array, so it can gain fields.
type document struct {
	About string           `json:"about"`
	Codes []httpx.CodeInfo `json:"codes"`
}

func errorCodes() ([]byte, error) {
	out, err := json.MarshalIndent(document{
		About: "Machine codes this API answers with in error.code. Generated by cmd/apicontract; " +
			"run `make api-contract` after changing them. The message beside the code on the wire " +
			"is for developers; clients translate the code themselves.",
		Codes: httpx.Catalog(),
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode the contract: %w", err)
	}
	return append(out, '\n'), nil
}

func main() {
	for _, c := range contracts {
		if err := write(c.file, c.build); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func write(file string, build func() ([]byte, error)) error {
	out, err := build()
	if err != nil {
		return err
	}
	path, err := contractPath(file)
	if err != nil {
		return err
	}
	// Narrow modes: git records only the executable bit anyway.
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, out, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	fmt.Printf("wrote %s\n", path)
	return nil
}
